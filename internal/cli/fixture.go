const fixtureOutDefault = "internal/store/storetest/testdata/quotes_fixture.sql"

func init() {
	Register(Command{Name: "fixture", Usage: "regen the clone-of-main test fixture: --db --out", Run: runFixture})
}

func runFixture(_ context.Context, cfg *config.Config, args []string) error {
	fs := flag.NewFlagSet("fixture", flag.ContinueOnError)
	dbPath := fs.String("db", cfg.Quotes.DBPath, "source SQLite database (seeded if empty)")
	outPath := fs.String("out", fixtureOutDefault, "output SQL fixture path")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if fs.NArg() > 0 {
		return fmt.Errorf("fixture: unexpected argument %q", fs.Arg(0))
	}
	if err := fixtureRun(*dbPath, *outPath); err != nil {
		return fmt.Errorf("fixture: %w", err)
	}
	printLine("wrote %s\n", *outPath)
	return nil
}

func fixtureRun(dbPath, outPath string) error {
	st, err := store.Open(dbPath)
	if err != nil {
		return err
	}
	defer func() { _ = st.Close() }()
	if err := seed.EnsureSeeded(st.DB()); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("-- Clone of the main quotes database; generated by qm fixture; do not edit.\n")
	b.WriteString("-- Loaded by internal/store/storetest.CloneFixture into a temp DB per test.\n")
	for _, tb := range fixtureTables {
		if err := dumpFixtureTable(&b, st.DB(), tb); err != nil {
			return fmt.Errorf("dump %s: %w", tb.name, err)
		}
	}
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return err
	}
	return os.WriteFile(outPath, []byte(b.String()), 0o644)
}

var fixtureTables = []fixtureTable{
	{"quotes", []string{"id", "sutta_id", "citation", "body_md", "body_text", "line_count", "char_count", "sources"}, "id"},
	{"collections", []string{"id", "name"}, "id"},
	{"collection_items", []string{"collection_id", "quote_id", "position", "group_id"}, "collection_id, position"},
	{"collection_groups", []string{"id", "collection_id", "name", "position"}, "collection_id, position"},
	{"collection_sutta_items", []string{"collection_id", "muid", "position", "group_id"}, "collection_id, position"},
	{"suttas", []string{"muid", "display", "link", "length"}, "muid"},
	{"categories", []string{"id", "name"}, "id"},
	{"category_items", []string{"category_id", "quote_id"}, "category_id, quote_id"},
}

type fixtureTable struct {
	name    string
	columns []string
	orderBy string
}

func dumpFixtureTable(b *strings.Builder, db *sql.DB, t fixtureTable) error {
	q := fmt.Sprintf("SELECT %s FROM %s ORDER BY %s", strings.Join(t.columns, ", "), t.name, t.orderBy)
	rs, err := db.Query(q)
	if err != nil {
		return err
	}
	defer func() { _ = rs.Close() }()
	cols := strings.Join(t.columns, ", ")
	for rs.Next() {
		vals := make([]any, len(t.columns))
		ptrs := make([]any, len(t.columns))
		for i := range vals {
			ptrs[i] = &vals[i]
		}
		if err := rs.Scan(ptrs...); err != nil {
			return err
		}
		fmt.Fprintf(b, "INSERT INTO %s (%s) VALUES (%s);\n", t.name, cols, formatValues(vals))
	}
	return rs.Err()
}

func formatValues(vals []any) string {
	parts := make([]string, len(vals))
	for i, v := range vals {
		parts[i] = formatValue(v)
	}
	return strings.Join(parts, ", ")
}

func formatValue(v any) string {
	switch x := v.(type) {
	case nil:
		return "NULL"
	case int64:
		return fmt.Sprintf("%d", x)
	case float64:
		return fmt.Sprintf("%g", x)
	case string:
		return sqlString(x)
	case []byte:
		return sqlString(string(x))
	default:
		return "NULL"
	}
}

func sqlString(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}
